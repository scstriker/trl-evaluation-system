# 不在职的样例专家（用于展示“不在职不参与分配”）
NOT_IN_SERVICE = {"魏东来"}


def seed_sample_experts(admin):
    """按 expert01～expert20 建立样例专家；已存在同名样例专家则跳过。返回新建数量。"""
    created = 0
    specialties = {s.code: s for s in Specialty.objects.all()}
    for index, (code, name, org, title, position, tags, page) in enumerate(SAMPLE_EXPERTS, start=1):
        if ExpertProfile.objects.filter(name=name, organization=org).exists():
            continue
        data = {
            "name": name,
            "organization": org,
            "title": title,
            "position": position,
            "specialty": specialties[code],
            "tags": tags,
            "in_service": name not in NOT_IN_SERVICE,
            "phone": f"138****{index:04d}",
            "email": f"expert{index:02d}@example.com",
        }
        if page:
            data.update(page)
        create_expert(data, admin, username=f"expert{index:02d}", is_sample=True)
        created += 1
    return created
